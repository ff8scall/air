export function getStationCoords(stationName: string): [number, number] | null {
  return STATION_COORDS_API[stationName] ?? STATION_COORDS[stationName] ?? null;
}

export function buildMapMarkers(items: SidoAirItem[]): MapMarkerData[] {
  return items
    .map((item) => {
      const coords =
        STATION_COORDS_API[item.stationName] ??
        STATION_COORDS[item.stationName];
      if (!coords) return null;

      return {
        stationName: item.stationName,
        lat: coords[0],
        lng: coords[1],
        pm10Value: item.pm10Value,
        pm25Value: item.pm25Value,
        khaiGrade: item.khaiGrade,
        sidoName: item.sidoName,
      } as MapMarkerData;
    })
    .filter((x): x is MapMarkerData => x !== null);
}
